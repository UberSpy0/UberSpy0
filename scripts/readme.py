"""Writes README.md: the hero, then the sections in the order profile.json lists them."""

from __future__ import annotations

from kit import CONFIG, FORMATS, ROOT
from projects import card_file
from sections import visible_sections


def img(src: str, alt: str, width: str = "100%") -> str:
    alt = alt.replace('"', "&quot;")
    return f'<img src="assets/{src}" width="{width}" alt="{alt}"/>'


def projects_block(repos: list[dict]) -> list[str]:
    if not repos:
        return ["_Public projects will show up here once they're on GitHub._"]
    width = "100%" if FORMATS.get("projects", "grid") == "list" else "49%"
    cards = [
        f'<a href="{r["url"]}">{img(card_file(i), r["nameWithOwner"], width)}</a>'
        for i, r in enumerate(repos)
    ]
    if width == "100%":
        return cards
    # Two per line, on one source line each so GitHub keeps them side by side.
    return [" ".join(cards[i:i + 2]) for i in range(0, len(cards), 2)]


def readme(repos: list[dict]) -> None:
    roles = ", ".join(r["text"] for r in CONFIG["roles"])
    blocks = [img("hero.svg", f'{CONFIG["name"]} — {roles}')]
    for s in visible_sections():
        key = s["id"]
        blocks.append(img(f"h-{key}.svg", s["title"]))
        if key == "about":
            blocks.append("\n".join(f"- {line}" for line in CONFIG["about"]))
        elif key == "projects":
            blocks += projects_block(repos)
        elif key == "achievements":
            alt = " · ".join(f'{a["name"]} {a["meta"][:4]}: {a["result"]}' for a in CONFIG["achievements"])
            blocks.append(img("achievements.svg", alt))
        elif key == "stack":
            blocks.append(img("stack.svg", "Tech stack"))
        elif key == "activity":
            blocks.append(img("github.svg", "GitHub activity for the last 12 months, updated automatically"))
            if FORMATS.get("show_now_building", True):
                blocks.append(img("now.svg", "What I'm working on right now, updated automatically"))
        elif key == "contact":
            tg = CONFIG["contact"]["telegram"]
            blocks.append(f'<a href="https://t.me/{tg}">{img("telegram.svg", f"Message me on Telegram: @{tg}", "260")}</a>')
    text = (
        "<!-- Generated by scripts/build.py from profile.json. Edit those, not this file. -->\n\n"
        + "\n\n".join(blocks) + "\n"
    )
    (ROOT / "README.md").write_text(text, encoding="utf-8")
    print("README.md written")
